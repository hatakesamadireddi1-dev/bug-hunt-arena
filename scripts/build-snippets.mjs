// Regenerates src/snippets.ts from snippets/*.txt (the human-editable source).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join, dirname } from "node:path";
import { loadAllSnippets } from "./parse-snippets.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const all = loadAllSnippets();
const body = `// GENERATED by scripts/build-snippets.mjs from snippets/*.txt. Do not edit by hand.
export type Language = "python" | "javascript" | "java" | "c";
export type Difficulty = "easy" | "medium" | "hard" | "expert";
export interface Snippet {
  id: string;
  language: Language;
  difficulty: Difficulty;
  goal: string;
  code: string[];
  bugLine: number;
  explanation: string;
  fixed: string;
}
export const SNIPPETS: Snippet[] = ${JSON.stringify(all, null, 2)};
`;
writeFileSync(join(ROOT, "src", "snippets.ts"), body);
console.log(`Wrote ${all.length} snippets to src/snippets.ts`);
